const stlMeshCache = new Map<string, MeshGeometryData>();

/**
 * Fetches and caches a pre-compiled Windows Rust binary STL from `/output/*.stl`.
 */
export async function loadCachedRustStlMesh(
  stlUrl: string,
  density: number = 7850
): Promise<MeshGeometryData> {
  const cacheKey = `${stlUrl}_${density}`;
  const existing = stlMeshCache.get(cacheKey);
  if (existing) {
    return existing;
  }
  const res = await fetch(stlUrl);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} fetching ${stlUrl}`);
  }
  const buffer = await res.arrayBuffer();
  const mesh = parseStlBuffer(buffer, density, 1.0);
  stlMeshCache.set(cacheKey, mesh);
  return mesh;
}

export function getCachedRustStlCount(): number {
  return stlMeshCache.size;
}

/**
 * Returns the corresponding `/qa/artifacts/<model>_<mode>.png` URL generated by the
 * Windows WGPU `OffscreenRenderer` if a golden artifact exists for the given preset & shader mode.
 */
export function getWindowsWgpuArtifactUrl(
  presetId: string,
  renderMode: RenderMode
): string | null {
  const mapping = GOLDEN_WINDOWS_MAPPINGS[presetId];
  if (!mapping) return null;

  const supportedModes = new Set([
    'shaded',
    'wireframe',
    'normals',
    'backfaces',
    'boundary_edges',
  ]);
  const modeKey =
    renderMode === 'flat_shading'
      ? 'shaded'
      : supportedModes.has(renderMode)
        ? renderMode
        : 'shaded';

  return `/qa/artifacts/${mapping.artifactPrefix}_${modeKey}.png`;
}

/**
 * Probes whether the native Windows `mcp-cad-server.exe` HTTP/SSE daemon is reachable
 * on the given endpoint (default `http://127.0.0.1:8080`).
 * Only performs a live network fetch when `?bridge=live` is present in the URL or `forceProbe` is true,
 * preventing unnecessary localhost network requests in cloud preview environments.
 */
export async function probeWindowsMcpServer(
  endpointUrl: string = 'http://127.0.0.1:8080',
  forceProbe: boolean = false
): Promise<WindowsBridgeStatus> {
  const t0 = performance.now();
  const base = endpointUrl.replace(/\/+$/, '');

  const shouldProbeNetwork =
    forceProbe ||
    (typeof window !== 'undefined' &&
      window.location.search.includes('bridge=live'));

  if (shouldProbeNetwork && typeof fetch === 'function') {
    try {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 650);

      const res = await fetch(`${base}/mcp`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          jsonrpc: '2.0',
          id: 1,
          method: 'initialize',
          params: {
            protocolVersion: '2024-11-05',
            capabilities: {},
            clientInfo: { name: 'mcp-cad-unified-studio', version: '1.0.0' },
          },
        }),
        signal: controller.signal,
      });
      clearTimeout(timeout);

      if (res.ok) {
        const data = await res.json();
        const latencyMs = Number((performance.now() - t0).toFixed(1));
        return {
          mode: 'windows_exe_connected',
          endpointUrl: base,
          connectedToWindowsExe: true,
          serverVersion:
            data?.result?.serverInfo?.version || '0.1.0-windows-x64',
          activeToolsCount: 28,
          lastSyncTimestamp: new Date().toTimeString().slice(0, 8),
          latencyMs,
          rustStlCacheCount: stlMeshCache.size,
        };
      }
    } catch {
      // Localhost 8080 server not active; use unified hybrid kernel
    }
  }

  return {
    mode: 'unified_hybrid_kernel',
    endpointUrl: base,
    connectedToWindowsExe: false,
    serverVersion: '0.1.0-hybrid-wgpu-sync',
    activeToolsCount: 28,
    lastSyncTimestamp: new Date().toTimeString().slice(0, 8),
    latencyMs: 0.4,
    rustStlCacheCount: stlMeshCache.size,
  };
}

/**
 * Executes an MCP tool call over JSON-RPC 2.0 against a live Windows `mcp-cad-server.exe` instance.
 */
export async function executeRemoteWindowsMcpTool(
  endpointUrl: string,
  toolName: string,
  args: Record<string, any>
): Promise<{ ok: boolean; payload: any }> {
  const base = endpointUrl.replace(/\/+$/, '');
  const res = await fetch(`${base}/mcp`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      jsonrpc: '2.0',
      id: Date.now(),
      method: 'tools/call',
      params: {
        name: toolName,
        arguments: args,
      },
    }),
  });
  if (!res.ok) {
    throw new Error(`Windows MCP Server HTTP ${res.status}`);
  }
  const rpc = await res.json();
  if (rpc.error) {
    throw new Error(rpc.error.message || 'MCP JSON-RPC Error');
  }
  const textContent = rpc.result?.content?.find(
    (c: any) => c.type === 'text'
  )?.text;
  const parsed = textContent ? JSON.parse(textContent) : rpc.result;
  return {
    ok: !rpc.result?.isError,
    payload: parsed,
  };
}
