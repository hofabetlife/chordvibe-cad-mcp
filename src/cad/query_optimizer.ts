function cloneDag(dag: DagNode[]): DagNode[] {
  return dag.map((n) => ({
    ...n,
    params: JSON.parse(JSON.stringify(n.params || {})),
  }));
}

function getBaseBoundingHalfExtents(rootNode: DagNode | undefined): [number, number, number] {
  if (!rootNode) return [0.05, 0.05, 0.05];
  const p = rootNode.params || {};
  switch (rootNode.type) {
    case 'box':
      return [
        Number(p.width ?? 0.08) * 0.5,
        Number(p.height ?? 0.04) * 0.5,
        Number(p.depth ?? 0.05) * 0.5,
      ];
    case 'cylinder': {
      const r = Number(p.radius ?? 0.025);
      const h = Number(p.height ?? 0.08);
      return [r, h * 0.5, r];
    }
    case 'polygon_prism': {
      const r = Number(p.outer_radius ?? 0.01);
      const h = Number(p.height ?? 0.01);
      return [r, h * 0.5, r];
    }
    case 'sphere': {
      const r = Number(p.radius ?? 0.035);
      return [r, r, r];
    }
    default:
      return [0.25, 0.25, 0.25];
  }
}

/**
 * Computes the SQL-like Cost Model for any candidate CAD DAG plan:
 * Cost = w1 * Time_est + w2 * SliverRisk + w3 * FullMeshPasses * 15 + w4 * BSPDepth^2 * 18
 */
export function estimateDagPlanCost(
  dag: DagNode[],
  quality: QualityPreset = 'standard'
): { cost: CadPlanCostBreakdown; explainTree: string[] } {
  const segMult = quality === 'draft' ? 0.6 : quality === 'standard' ? 1.0 : 1.8;
  let estimatedTimeMs = 0.4;
  let estimatedTriangles = 0;
  let sliverRiskScore = 0;
  let bspSplitDepth = 0;
  let fullMeshPasses = 0;
  const explainTree: string[] = [];

  for (let i = 0; i < dag.length; i++) {
    const node = dag[i];
    if (!node.enabled) {
      explainTree.push(
        `  -> [DisabledOp] ${node.name} (cost=0.0..0.5, skipped_at_eval=true)`
      );
      estimatedTimeMs += 0.1;
      continue;
    }

    const p = node.params || {};
    switch (node.type) {
      case 'box': {
        const opCost = 1.2;
        estimatedTimeMs += 0.3;
        estimatedTriangles += 12;
        fullMeshPasses += 1;
        explainTree.push(
          `  -> [AnalyticalScan: Box] ${node.name} (cost=0.0..${opCost.toFixed(1)} tris=12 sliver_risk=0%)`
        );
        break;
      }
      case 'cylinder':
      case 'cone': {
        const tris = Math.round(256 * segMult);
        const opCost = 4.5 * segMult;
        estimatedTimeMs += 0.9 * segMult;
        estimatedTriangles += tris;
        fullMeshPasses += 1;
        explainTree.push(
          `  -> [AnalyticalScan: ${node.type.toUpperCase()}] ${node.name} (cost=0.0..${opCost.toFixed(1)} tris=${tris} sliver_risk=0%)`
        );
        break;
      }
      case 'revolve': {
        const hasInner = Number(p.inner_radius ?? 0) > 1e-6;
        const tris = Math.round((hasInner ? 512 : 384) * segMult);
        const opCost = (hasInner ? 6.8 : 5.5) * segMult;
        estimatedTimeMs += 1.1 * segMult;
        estimatedTriangles += tris;
        fullMeshPasses += 1;
        explainTree.push(
          `  -> [IndexOnlyRevolve2D${hasInner ? ' (Annular g=1)' : ''}] ${node.name} (cost=0.0..${opCost.toFixed(1)} tris=${tris} sliver_risk=0%)`
        );
        break;
      }
      case 'polygon_prism': {
        const hasFusedThread = Number(p.thread_pitch ?? 0) > 0;
        const hasFusedBore = Number(p.bore_radius ?? 0) > 0;
        const tris = hasFusedThread ? 4200 : hasFusedBore ? 760 : 120;
        const opCost = hasFusedThread ? 16.5 : hasFusedBore ? 8.2 : 3.5;
        estimatedTimeMs += hasFusedThread ? 2.4 : 0.8;
        estimatedTriangles += tris;
        fullMeshPasses += 1;
        explainTree.push(
          `  -> [AnalyticalPrismKernel${hasFusedThread ? '+Bore+Thread' : hasFusedBore ? '+Bore' : ''}] ${node.name} (cost=0.0..${opCost.toFixed(1)} tris=${tris} sliver_risk=0%)`
        );
        break;
      }
      case 'spur_gear':
      case 'wheel_rim': {
        const tris = node.type === 'spur_gear' ? 2800 : 3600;
        const opCost = 14.0;
        estimatedTimeMs += 2.2;
        estimatedTriangles += tris;
        fullMeshPasses += 1;
        explainTree.push(
          `  -> [ParametricBRepKernel: ${node.type}] ${node.name} (cost=0.0..${opCost.toFixed(1)} tris=${tris} sliver_risk=0%)`
        );
        break;
      }
      case 'boolean_difference':
      case 'boolean_union':
      case 'boolean_intersection': {
        bspSplitDepth += 1;
        fullMeshPasses += 1;
        const depthPenalty = bspSplitDepth * 28.0;
        estimatedTimeMs += 3.8 * bspSplitDepth;
        estimatedTriangles += Math.round(320 * bspSplitDepth);
        sliverRiskScore = Math.min(98, sliverRiskScore + 22 * bspSplitDepth);
        explainTree.push(
          `  -> [NestedLoop3D_CSG: ${node.type.replace('boolean_', '').toUpperCase()}] ${node.name} (cost=18.0..${(42 + depthPenalty).toFixed(1)} bsp_depth=${bspSplitDepth} sliver_risk=+${22 * bspSplitDepth}%)`
        );
        break;
      }
      case 'cut_hole': {
        bspSplitDepth += 1;
        fullMeshPasses += 1;
        const isBatched = Boolean(p.de_morgan_batched);
        const stepCost = isBatched ? 12.0 : 24.0 + bspSplitDepth * 14.0;
        estimatedTimeMs += isBatched ? 1.1 : 2.6 + bspSplitDepth * 0.8;
        estimatedTriangles += 256;
        sliverRiskScore = Math.min(
          95,
          sliverRiskScore + (isBatched ? 4 : 14 * bspSplitDepth)
        );
        explainTree.push(
          `  -> [${isBatched ? 'VectorizedDeMorganBore' : 'SequentialCSGBore'}: cut_hole] ${node.name} (cost=8.0..${stepCost.toFixed(1)} tris=+256)`
        );
        break;
      }
      case 'cut_helical_groove': {
        bspSplitDepth += 1;
        fullMeshPasses += 1;
        const stepCost = 48.0 + bspSplitDepth * 16.0;
        estimatedTimeMs += 4.5;
        estimatedTriangles += 3400;
        sliverRiskScore = Math.min(95, sliverRiskScore + 18);
        explainTree.push(
          `  -> [HelicalSweepCSG: cut_helical_groove] ${node.name} (cost=22.0..${stepCost.toFixed(1)} tris=+3400)`
        );
        break;
      }
      case 'transform': {
        fullMeshPasses += 1;
        const stepCost = 14.5;
        estimatedTimeMs += 1.2;
        explainTree.push(
          `  -> [FullVertexBufferScan: transform] ${node.name} (cost=4.0..${stepCost.toFixed(1)} matrix_4x4=true)`
        );
        break;
      }
      default: {
        fullMeshPasses += 1;
        estimatedTimeMs += 1.0;
        explainTree.push(`  -> [MeshOp: ${node.type}] ${node.name} (cost=1.0..10.0)`);
        break;
      }
    }
  }

  const totalCostScore = Number(
    (
      estimatedTimeMs * 8.5 +
      sliverRiskScore * 1.45 +
      fullMeshPasses * 9.0 +
      bspSplitDepth * bspSplitDepth * 11.5
    ).toFixed(1)
  );

  explainTree.unshift(
    `Gather SolidMesh (cost=0.00..${totalCostScore.toFixed(1)} passes=${fullMeshPasses} est_time=${estimatedTimeMs.toFixed(1)}ms sliver_risk=${sliverRiskScore}%)`
  );

  return {
    cost: {
      estimatedTimeMs: Number(estimatedTimeMs.toFixed(2)),
      estimatedTriangles,
      sliverRiskScore: Math.round(sliverRiskScore),
      bspSplitDepth,
      fullMeshPasses,
      totalCostScore,
    },
    explainTree,
  };
}

/**
 * Rule-Based Optimization (RBO):
 * Applies R1 (Transform Fusion & Identity Elimination),
 * R2 (Spatial AABB Out-of-Bounds & Disabled Node Culling),
 * and R3 (De Morgan CSG Union Pushdown & Duplicate Bore Elimination).
 */
function buildRuleOptimizedPlan(
  originalDag: DagNode[],
  quality: QualityPreset
): { dag: DagNode[]; rules: AppliedRewriteRule[] } {
  const working = cloneDag(originalDag);
  const rules: AppliedRewriteRule[] = [];

  // 1. R2: Disabled node & Spatial AABB Out-of-Bounds Culling
  const rootNode = working.find((n) => n.enabled);
  const [halfW, , halfD] = getBaseBoundingHalfExtents(rootNode);
  let culledCount = 0;
  const afterCulling: DagNode[] = [];

  for (const node of working) {
    if (!node.enabled) {
      culledCount++;
      continue;
    }
    if (node.type === 'cut_hole') {
      const pos = Array.isArray(node.params?.position)
        ? node.params.position
        : [0, 0, 0];
      const r = Number(node.params?.radius ?? 0.005);
      // Check if bore center is completely outside base X/Z footprint
      if (Math.abs(pos[0]) - r > halfW * 1.05 || Math.abs(pos[2]) - r > halfD * 1.05) {
        culledCount++;
        continue;
      }
    }
    afterCulling.push(node);
  }

  if (culledCount > 0) {
    rules.push({
      ruleId: 'R2_AABB_DEAD_OP_CULLING',
      title: 'R2: Отсечение пустых узлов по AABB (Spatial Partition Pruning)',
      sqlAnalogy: 'Partition Pruning / Dead Predicate Elimination (WHERE 1=0)',
      description: `Удалено ${culledCount} операций, не пересекающих габаритный бокс (AABB) базового тела или отключенных в дереве.`,
      nodesRemoved: culledCount,
      costSaved: Number((culledCount * 38.5).toFixed(1)),
    });
  }

  // 2. R1: Affine Transform Matrix Fusion & Identity Elimination
  const nonTransforms: DagNode[] = [];
  const transformNodes: DagNode[] = [];
  for (const node of afterCulling) {
    if (node.type === 'transform') {
      transformNodes.push(node);
    } else {
      nonTransforms.push(node);
    }
  }

  if (transformNodes.length > 0) {
    let tx = 0,
      ty = 0,
      tz = 0;
    let rx = 0,
      ry = 0,
      rz = 0;
    let sx = 1,
      sy = 1,
      sz = 1;

    for (const tn of transformNodes) {
      const tr = tn.params?.translation || [0, 0, 0];
      const rot = tn.params?.rotation_deg || [0, 0, 0];
      const sc = tn.params?.scale || [1, 1, 1];
      tx += Number(tr[0] ?? 0);
      ty += Number(tr[1] ?? 0);
      tz += Number(tr[2] ?? 0);
      rx += Number(rot[0] ?? 0);
      ry += Number(rot[1] ?? 0);
      rz += Number(rot[2] ?? 0);
      sx *= Number(sc[0] ?? 1);
      sy *= Number(sc[1] ?? 1);
      sz *= Number(sc[2] ?? 1);
    }

    const isIdentity =
      Math.hypot(tx, ty, tz) < 1e-6 &&
      Math.hypot(rx, ry, rz) < 1e-4 &&
      Math.abs(sx - 1) < 1e-5 &&
      Math.abs(sy - 1) < 1e-5 &&
      Math.abs(sz - 1) < 1e-5;

    if (isIdentity) {
      rules.push({
        ruleId: 'R1_TRANSFORM_FUSION',
        title: 'R1: Свертка матриц трансформации в Единичную (Identity Elimination)',
        sqlAnalogy: 'Constant Folding & Projection Collapse',
        description: `Свернуто ${transformNodes.length} матричных трансформаций (4×4) в единичную матрицу I; лишние проходы по буферу вершин полностью исключены.`,
        nodesRemoved: transformNodes.length,
        costSaved: Number((transformNodes.length * 26.0).toFixed(1)),
      });
    } else if (transformNodes.length > 1) {
      nonTransforms.push({
        id: 'node_fused_transform',
        name: `Fused 4×4 Transform [${(tx * 1000).toFixed(1)}, ${(ty * 1000).toFixed(1)}, ${(tz * 1000).toFixed(1)}mm]`,
        type: 'transform',
        params: {
          translation: [Number(tx.toFixed(6)), Number(ty.toFixed(6)), Number(tz.toFixed(6))],
          rotation_deg: [Number(rx.toFixed(3)), Number(ry.toFixed(3)), Number(rz.toFixed(3))],
          scale: [Number(sx.toFixed(5)), Number(sy.toFixed(5)), Number(sz.toFixed(5))],
        },
        enabled: true,
      });
      rules.push({
        ruleId: 'R1_TRANSFORM_FUSION',
        title: 'R1: Композиция аффинных матриц M = M_n · ... · M_1',
        sqlAnalogy: 'Constant Folding & Expression Simplification',
        description: `Объединено ${transformNodes.length} последовательных трансформаций в один матричный проход.`,
        nodesRemoved: transformNodes.length - 1,
        costSaved: Number(((transformNodes.length - 1) * 24.5).toFixed(1)),
      });
    } else {
      nonTransforms.push(transformNodes[0]);
    }
  }

  // 3. R3: De Morgan CSG Subtract Pushdown & Duplicate Bore Elimination
  // A \ B1 \ B2 ... -> A \ Union(B1, B2) and remove redundant boolean_difference markers when paired with cut_hole
  const seenHoles = new Set<string>();
  const afterDeMorgan: DagNode[] = [];
  let removedByDeMorgan = 0;
  const hasCutHole = nonTransforms.some((n) => n.type === 'cut_hole');

  for (const node of nonTransforms) {
    if (node.type === 'boolean_difference' && hasCutHole) {
      removedByDeMorgan++;
      continue;
    }
    if (node.type === 'cut_hole') {
      const pos = node.params?.position || [0, 0, 0];
      const norm = node.params?.normal || [0, 0, -1];
      const r = Number(node.params?.radius ?? 0.005);
      const d = Number(node.params?.depth ?? 0.04);
      const sig = `${Number(pos[0]).toFixed(4)}_${Number(pos[1]).toFixed(4)}_${Number(pos[2]).toFixed(4)}_${Number(norm[0]).toFixed(2)}_${Number(norm[1]).toFixed(2)}_${Number(norm[2]).toFixed(2)}_${r.toFixed(4)}_${d.toFixed(4)}`;
      if (seenHoles.has(sig)) {
        removedByDeMorgan++;
        continue;
      }
      seenHoles.add(sig);
      afterDeMorgan.push({
        ...node,
        name:
          seenHoles.size > 1
            ? `${node.name} [De Morgan Batch #${seenHoles.size}]`
            : node.name,
        params: {
          ...node.params,
          de_morgan_batched: true,
        },
      });
    } else {
      afterDeMorgan.push(node);
    }
  }

  if (removedByDeMorgan > 0 || seenHoles.size > 1) {
    rules.push({
      ruleId: 'R3_DEMORGAN_CSG_BATCH',
      title: 'R3: Закон Де Моргана A \\ (B₁ ∪ B₂ ∪ ... ∪ Bₖ) и дедупликация CSG',
      sqlAnalogy: 'Predicate Pushdown & Hash-Join Batching',
      description:
        removedByDeMorgan > 0
          ? `Устранено ${removedByDeMorgan} дублирующих/промежуточных 3D CSG-вычитаний; ${seenHoles.size} отверстий сгруппированы в единый батч-проход без каскадного дробления сетки.`
          : `Сгруппировано ${seenHoles.size} последовательных сверлений в единый батч-проход A \\ (B₁ ∪ B₂) вместо каскадного BSP-деления.`,
      nodesRemoved: removedByDeMorgan,
      costSaved: Number((removedByDeMorgan * 46.0 + seenHoles.size * 18.0).toFixed(1)),
    });
  }

  // Ensure we don't return an empty DAG
  if (afterDeMorgan.length === 0 && originalDag.length > 0) {
    afterDeMorgan.push(cloneDag([originalDag[0]])[0]);
  }

  return { dag: afterDeMorgan, rules };
}

/**
 * Cost-Based Strength Reduction (CBO Physical Operator Selection):
 * Checks if 3D CSG operations on coaxial bodies can be lowered into 1-pass Analytical Kernels:
 * - R4: Coaxial Cylinder + Through CutHole -> 2D Annular Revolve (0 CSG splits, 0 sliver triangles)
 * - R5: PolygonPrism + Coaxial CutHole + Helical Thread -> Single Analytical Threaded Prism Kernel
 */
function buildAnalyticalKernelPlan(
  rboDag: DagNode[],
  rboRules: AppliedRewriteRule[]
): { dag: DagNode[]; rules: AppliedRewriteRule[] } | null {
  const working = cloneDag(rboDag);
  const rules = [...rboRules];

  // Check R4: Base Cylinder + Coaxial Through-Hole (no keyway) -> Annular 2D Profile Revolve
  if (
    working.length >= 2 &&
    working[0].type === 'cylinder' &&
    working[1].type === 'cut_hole'
  ) {
    const cylP = working[0].params || {};
    const holeP = working[1].params || {};
    const rOut = Number(cylP.radius ?? 0.025);
    const h = Number(cylP.height ?? 0.06);
    const rIn = Number(holeP.radius ?? 0.01);
    const depth = Number(holeP.depth ?? h);
    const pos = holeP.position || [0, 0, 0];
    const hasKeyway = Number(holeP.keyway_width ?? 0) > 1e-5;

    const isCoaxial = Math.hypot(Number(pos[0] ?? 0), Number(pos[2] ?? 0)) < 1e-3;
    const isThrough = depth >= h * 0.85;

    if (isCoaxial && isThrough && !hasKeyway && rIn > 1e-4 && rIn < rOut * 0.92) {
      const halfH = Number((h * 0.5).toFixed(5));
      const revolveNode: DagNode = {
        id: 'node_opt_revolve_annular',
        name: `Optimized 2D Annular Revolve (R_in=${(rIn * 1000).toFixed(1)}..R_out=${(rOut * 1000).toFixed(1)}mm)`,
        type: 'revolve',
        params: {
          profile: [
            [rOut, -halfH],
            [rOut, halfH],
          ],
          inner_radius: rIn,
          angle_deg: 360,
        },
        enabled: true,
      };

      const remaining = working.slice(2);
      rules.push({
        ruleId: 'R4_COAXIAL_REVOLVE_REDUCTION',
        title: 'R4: Понижение размерности 3D CSG → 2D Профиль вращения (Revolve)',
        sqlAnalogy: 'Full Table Scan + Filter → Index-Only Scan (Strength Reduction)',
        description: `Соосное 3D-вычитание цилиндров (R=${(rOut * 1000).toFixed(1)}мм \\ r=${(rIn * 1000).toFixed(1)}мм) заменено на 1-проходное аналитическое вращение 2D-контура (Annular Revolve 360°). Риск вырожденных треугольников снижен до 0%.`,
        nodesRemoved: 1,
        costSaved: 64.0,
      });

      return {
        dag: [revolveNode, ...remaining],
        rules,
      };
    }
  }

  // Check R5: PolygonPrism + Coaxial CutHole + Helical Groove -> Single Fused Analytical Prism Kernel
  if (working.length >= 2 && working[0].type === 'polygon_prism') {
    const prismP = { ...(working[0].params || {}) };
    let boreNodeIdx = -1;
    let helixNodeIdx = -1;

    for (let i = 1; i < working.length; i++) {
      const n = working[i];
      if (n.type === 'cut_hole' && boreNodeIdx === -1) {
        const pos = n.params?.position || [0, 0, 0];
        if (Math.hypot(Number(pos[0] ?? 0), Number(pos[2] ?? 0)) < 1e-3) {
          boreNodeIdx = i;
        }
      } else if (n.type === 'cut_helical_groove' && helixNodeIdx === -1) {
        helixNodeIdx = i;
      }
    }

    if (boreNodeIdx !== -1 || helixNodeIdx !== -1) {
      let fusedOps = 0;
      if (boreNodeIdx !== -1) {
        prismP.bore_radius = Number(working[boreNodeIdx].params?.radius ?? 0.00425);
        fusedOps++;
      }
      if (helixNodeIdx !== -1) {
        const hp = working[helixNodeIdx].params || {};
        prismP.thread_pitch = Number(hp.pitch ?? 0.0015);
        prismP.thread_depth = Number(hp.groove_radius ?? 0.0008);
        if (!prismP.bore_radius) {
          prismP.bore_radius = Number(hp.helix_radius ?? 0.005) * 0.85;
        }
        fusedOps++;
      }

      const fusedPrismNode: DagNode = {
        id: 'node_opt_fused_prism',
        name: `Analytical Threaded Prism Kernel (DIN 934 + ISO 68-1 Fused)`,
        type: 'polygon_prism',
        params: prismP,
        enabled: true,
      };

      const remaining = working.filter(
        (_, idx) => idx !== 0 && idx !== boreNodeIdx && idx !== helixNodeIdx
      );

      rules.push({
        ruleId: 'R5_ANALYTICAL_PRISM_THREAD_FUSION',
        title: 'R5: Проталкивание резьбы и отверстия в ядро призмы (Kernel Pushdown)',
        sqlAnalogy: 'Subquery Flattening & Index Pushdown',
        description: `Свернуты ${fusedOps + 1} операций (Шестигранная призма + Центровое отверстие + Винтовая резьба ISO 68-1) в единый аналитический проход генератора сетки без промежуточной перестройки топологии.`,
        nodesRemoved: fusedOps,
        costSaved: Number((fusedOps * 42.0).toFixed(1)),
      });

      return {
        dag: [fusedPrismNode, ...remaining],
        rules,
      };
    }
  }

  return null;
}

/**
 * Runs the Cost-Based CAD Query Optimizer (`EXPLAIN ANALYZE` for Solid Modeling DAGs).
 * Generates candidate physical execution plans, scores them with the geometric cost model,
 * verifies volumetric & topological invariants (Volume, Euler Genus, Watertightness),
 * and selects the cheapest plan.
 */
export function optimizeCadFeatureTree(
  partId: string,
  partName: string,
  originalDag: DagNode[],
  quality: QualityPreset = 'standard',
  density: number = 7850
): CadQueryOptimizationReport {
  // 1. Plan 1: Naive Sequential Plan (As-Written by AI / User)
  const naiveEval = estimateDagPlanCost(originalDag, quality);
  const naivePlan: CadExecutionPlan = {
    planId: 'plan_naive_seq',
    strategyName: 'Plan A: Naive Sequential Execution (As-Written)',
    sqlEquivalent: 'SeqScan + NestedLoop 3D CSG + Unfused Matrix Passes',
    isSelectedBest: false,
    dag: cloneDag(originalDag),
    appliedRules: [],
    costBreakdown: naiveEval.cost,
    explainTree: naiveEval.explainTree,
  };

  // 2. Plan 2: Rule-Based Optimized Plan (RBO: Transform Fusion + AABB Pruning + De Morgan Batching)
  const rboBuilt = buildRuleOptimizedPlan(originalDag, quality);
  const rboEval = estimateDagPlanCost(rboBuilt.dag, quality);
  const rboPlan: CadExecutionPlan = {
    planId: 'plan_rbo_batch',
    strategyName: 'Plan B: Algebraic Rule-Optimized Plan (RBO)',
    sqlEquivalent: 'AABB Partition Pruning + Matrix Folding + De Morgan Hash-CSG',
    isSelectedBest: false,
    dag: rboBuilt.dag,
    appliedRules: rboBuilt.rules,
    costBreakdown: rboEval.cost,
    explainTree: rboEval.explainTree,
  };

  const candidatePlans: CadExecutionPlan[] = [naivePlan, rboPlan];

  // 3. Plan 3: Cost-Based Analytical Kernel Plan (CBO Strength Reduction: 3D CSG -> 2D Revolve / Fused Kernel)
  const cboBuilt = buildAnalyticalKernelPlan(rboBuilt.dag, rboBuilt.rules);
  if (cboBuilt) {
    const cboEval = estimateDagPlanCost(cboBuilt.dag, quality);
    const cboPlan: CadExecutionPlan = {
      planId: 'plan_cbo_analytical',
      strategyName: 'Plan C: Analytical Strength-Reduced Plan (CBO Kernel)',
      sqlEquivalent: 'Index-Only 2D Revolve / Fused Analytical Kernel Pushdown',
      isSelectedBest: false,
      dag: cboBuilt.dag,
      appliedRules: cboBuilt.rules,
      costBreakdown: cboEval.cost,
      explainTree: cboEval.explainTree,
    };
    candidatePlans.push(cboPlan);
  }

  // Pick the plan with the minimum totalCostScore
  let bestPlan = candidatePlans[0];
  for (const cand of candidatePlans) {
    if (cand.costBreakdown.totalCostScore < bestPlan.costBreakdown.totalCostScore) {
      bestPlan = cand;
    }
  }
  bestPlan.isSelectedBest = true;

  // Verify geometric & topological equivalence between Naive Plan and Best Plan
  const meshBefore = evaluateFeatureTree(originalDag, quality, density);
  const meshAfter = evaluateFeatureTree(bestPlan.dag, quality, density);

  const volBefore = meshBefore.volume;
  const volAfter = meshAfter.volume;
  const volumeDeltaPct =
    volBefore > 1e-12
      ? Number(((Math.abs(volAfter - volBefore) / volBefore) * 100).toFixed(3))
      : 0;

  const equivalenceVerified =
    meshAfter.isWatertight &&
    meshAfter.eulerGenus === meshBefore.eulerGenus &&
    volumeDeltaPct < 2.0;

  const originalCost = naivePlan.costBreakdown.totalCostScore;
  const optimalCost = bestPlan.costBreakdown.totalCostScore;
  const costReductionPct =
    originalCost > 0
      ? Number(
          Math.max(0, ((originalCost - optimalCost) / originalCost) * 100).toFixed(1)
        )
      : 0;

  const origSliver = naivePlan.costBreakdown.sliverRiskScore;
  const optSliver = bestPlan.costBreakdown.sliverRiskScore;
  const sliverRiskReductionPct =
    origSliver > 0
      ? Number(Math.max(0, ((origSliver - optSliver) / origSliver) * 100).toFixed(1))
      : 0;

  const speedupFactor =
    bestPlan.costBreakdown.estimatedTimeMs > 0
      ? Number(
          Math.max(
            1.0,
            naivePlan.costBreakdown.estimatedTimeMs /
              bestPlan.costBreakdown.estimatedTimeMs
          ).toFixed(2)
        )
      : 1.0;

  return {
    partId,
    partName,
    originalNodeCount: originalDag.length,
    optimalNodeCount: bestPlan.dag.length,
    originalCost,
    optimalCost,
    costReductionPct,
    sliverRiskReductionPct,
    speedupFactor,
    invariantCheck: {
      volumeBeforeM3: Number(volBefore.toFixed(7)),
      volumeAfterM3: Number(volAfter.toFixed(7)),
      volumeDeltaPct,
      genusBefore: meshBefore.eulerGenus,
      genusAfter: meshAfter.eulerGenus,
      watertightBefore: meshBefore.isWatertight,
      watertightAfter: meshAfter.isWatertight,
      equivalenceVerified,
    },
    candidatePlans,
    bestPlan,
  };
}
