/// Individual modeling feature operation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum FeatureOp {
    /// Add a box centered at the origin.
    AddBox {
        width: f64,
        height: f64,
        depth: f64,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a cylinder centered along Z.
    AddCylinder {
        radius: f64,
        height: f64,
        #[serde(default = "default_segments")]
        segments: usize,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a regular polygonal prism (e.g. Hexagonal nut/bolt head) centered along Z.
    AddPolygonPrism {
        #[serde(default = "default_polygon_sides")]
        sides: usize,
        height: f64,
        #[serde(default)]
        width_across_flats: Option<f64>,
        #[serde(default)]
        radius: Option<f64>,
        #[serde(default)]
        chamfer: Option<f64>,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a UV sphere centered at the origin.
    AddSphere {
        radius: f64,
        #[serde(default = "default_sectors")]
        sectors: usize,
        #[serde(default = "default_stacks")]
        stacks: usize,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a cone or frustum centered along Z.
    AddCone {
        radius_bottom: f64,
        radius_top: f64,
        height: f64,
        #[serde(default = "default_segments")]
        segments: usize,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a parametric involute spur gear centered along Z.
    AddSpurGear {
        module: f64,
        teeth: usize,
        #[serde(default = "default_pressure_angle_deg")]
        pressure_angle_deg: f64,
        face_width: f64,
        #[serde(default)]
        bore_radius: Option<f64>,
        #[serde(default)]
        keyway_width: Option<f64>,
        #[serde(default)]
        keyway_depth: Option<f64>,
        #[serde(default)]
        hub_diameter: Option<f64>,
        #[serde(default)]
        hub_length: Option<f64>,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a solid of revolution generated by revolving a 2D profile [r, z] around the Z axis.
    AddRevolve {
        profile: Vec<[f64; 2]>,
        #[serde(default = "default_revolve_angle")]
        angle_deg: f64,
        #[serde(default = "default_segments")]
        segments: usize,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Add a parametric automotive wheel rim with stepped barrel, central hub, PCD bolt pattern, and spokes.
    AddWheelRim {
        rim_diameter: f64,
        rim_width: f64,
        #[serde(default)]
        flange_diameter: Option<f64>,
        #[serde(default)]
        hub_diameter: Option<f64>,
        #[serde(default)]
        hub_bore_diameter: Option<f64>,
        #[serde(default)]
        pcd_diameter: Option<f64>,
        #[serde(default = "default_bolt_holes_count")]
        bolt_holes_count: Option<usize>,
        #[serde(default = "default_bolt_hole_diameter")]
        bolt_hole_diameter: Option<f64>,
        #[serde(default = "default_spokes_count")]
        spokes_count: Option<usize>,
        #[serde(default)]
        spoke_width: Option<f64>,
        #[serde(default)]
        spoke_thickness: Option<f64>,
        #[serde(default)]
        offset_et: Option<f64>,
        #[serde(default)]
        position: Option<[f64; 3]>,
        #[serde(default)]
        rotation_deg: Option<[f64; 3]>,
    },
    /// Cut a cylindrical hole from the current solid, with optional DIN 6885 keyway.
    CutHole {
        center: [f64; 3],
        normal: [f64; 3],
        radius: f64,
        depth: f64,
        #[serde(default)]
        keyway_width: Option<f64>,
        #[serde(default)]
        keyway_depth: Option<f64>,
    },
    /// Cut a helical groove (flute) into the solid.
    CutHelicalGroove {
        helix_radius: f64,
        groove_radius: f64,
        pitch: f64,
        height: f64,
        start_z: f64,
        #[serde(default = "default_starts")]
        starts: usize,
        #[serde(default = "default_right_hand")]
        is_right_hand: bool,
        #[serde(default = "default_profile_type")]
        profile_type: String,
    },
    /// Subtract an arbitrary tool mesh from the solid.
    BooleanDifferenceMesh {
        tool_mesh: TriangleMesh,
    },
    /// Union an arbitrary tool mesh with the solid.
    BooleanUnionMesh {
        tool_mesh: TriangleMesh,
    },
    /// Intersect an arbitrary tool mesh with the solid.
    BooleanIntersectionMesh {
        tool_mesh: TriangleMesh,
    },
    /// Base or additive imported boundary mesh (e.g. from `import_stl`).
    ImportedMesh {
        mesh: TriangleMesh,
    },
    /// Apply spatial translation, rotation (RPY degrees), and scale factors.
    Transform {
        #[serde(default)]
        translation: [f64; 3],
        #[serde(default)]
        rotation_deg: [f64; 3],
        #[serde(default = "default_scale")]
        scale: [f64; 3],
    },
}

